/** Simple name of the Java annotation type that accepted TC annotations use. */
export const TC_ANNOTATION_NAME = 'TechnicalCredit';

/** File name of the generated annotation type. */
export const TC_ANNOTATION_FILE = `${TC_ANNOTATION_NAME}.java`;

/** Returns the package declared in a Java source file, or `null` for the default package. */
export function javaPackageOf(source: string): string | null {
  return source.match(/^\s*package\s+([\w.]+)\s*;/m)?.[1] ?? null;
}

/**
 * Source for the `@TechnicalCredit` annotation type. Retention is SOURCE so the
 * annotation documents the design without affecting bytecode or runtime.
 */
export function renderAnnotationTypeSource(pkg: string | null): string {
  return [
    ...(pkg ? [`package ${pkg};`, ''] : []),
    'import java.lang.annotation.Documented;',
    'import java.lang.annotation.ElementType;',
    'import java.lang.annotation.Repeatable;',
    'import java.lang.annotation.Retention;',
    'import java.lang.annotation.RetentionPolicy;',
    'import java.lang.annotation.Target;',
    '',
    '/** Records a Technical Credit design decision. Generated by the TechnicalCredit extension. */',
    '@Documented',
    '@Retention(RetentionPolicy.SOURCE)',
    '@Target({ElementType.TYPE, ElementType.METHOD, ElementType.FIELD})',
    `@Repeatable(${TC_ANNOTATION_NAME}.List.class)`,
    `public @interface ${TC_ANNOTATION_NAME} {`,
    '  String benefit();',
    '',
    '  String category();',
    '',
    '  String[] designPatterns() default {};',
    '',
    '  String conditions() default "";',
    '',
    '  String[] signals() default {};',
    '',
    '  String adr() default "";',
    '',
    '  /** Container that lets one declaration carry several Technical Credit annotations. */',
    '  @Documented',
    '  @Retention(RetentionPolicy.SOURCE)',
    '  @Target({ElementType.TYPE, ElementType.METHOD, ElementType.FIELD})',
    '  @interface List {',
    `    ${TC_ANNOTATION_NAME}[] value();`,
    '  }',
    '}',
    '',
  ].join('\n');
}

/** A single-line insertion into a Java source file. */
export interface LineInsertion {
  line: number;
  text: string;
}

/**
 * Returns the import line `source` needs to reference the annotation type in
 * `annotationPackage`, or `null` when it is already visible (same package,
 * explicit import, or wildcard import).
 */
export function requiredImport(
  source: string,
  annotationPackage: string | null,
): LineInsertion | null {
  const ownPackage = javaPackageOf(source);
  if (annotationPackage === ownPackage || annotationPackage === null) {
    return null;
  }

  const fqcn = `${annotationPackage}.${TC_ANNOTATION_NAME}`;
  const escaped = annotationPackage.replace(/\./g, '\\.');
  const alreadyImported = new RegExp(
    `^\\s*import\\s+(${escaped}\\.${TC_ANNOTATION_NAME}|${escaped}\\.\\*)\\s*;`,
    'm',
  ).test(source);
  if (alreadyImported) {
    return null;
  }

  const lines = source.split('\n');
  const lastImport = lines.reduce(
    (last, line, i) => (/^\s*import\s/.test(line) ? i : last),
    -1,
  );
  if (lastImport >= 0) {
    return { line: lastImport + 1, text: `import ${fqcn};\n` };
  }
  const packageLine = lines.findIndex((l) => /^\s*package\s/.test(l));
  return packageLine >= 0
    ? { line: packageLine + 1, text: `\nimport ${fqcn};\n` }
    : { line: 0, text: `import ${fqcn};\n\n` };
}
